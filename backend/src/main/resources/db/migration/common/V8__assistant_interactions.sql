-- One row per message to the voice assistant: what the user said, what the assistant replied,
-- and the sales it proposed. A proposal is only written to daily_sales when the user confirms it;
-- outcome records whether they confirmed it as proposed, edited it first, or cancelled it.
-- Used for confirming proposals and for evaluating the assistant. Audio is never stored.
CREATE TABLE assistant_interactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL CONSTRAINT assistant_interactions_owner_id_fkey REFERENCES app_users(id),
  conversation_id VARCHAR(64) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  page VARCHAR(64),
  input_mode VARCHAR(16) NOT NULL,
  user_text VARCHAR(2000) NOT NULL,
  detected_languages VARCHAR(64),
  reply VARCHAR(4000),
  model VARCHAR(64) NOT NULL,
  latency_ms INTEGER NOT NULL,
  -- NONE (no proposal), PENDING, CONFIRMED, EDITED, CANCELLED or EXPIRED
  outcome VARCHAR(16) NOT NULL,
  proposal_json VARCHAR(20000),
  final_json VARCHAR(20000),
  resolved_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX assistant_interactions_owner_id_idx ON assistant_interactions(owner_id);
