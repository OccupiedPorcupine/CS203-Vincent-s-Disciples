-- What each account's use of the assistant costs, and the limits on it (issue #65).
-- plan sets the daily allowances (FREE, STANDARD or PRO; see AssistantPlan).
ALTER TABLE app_users ADD COLUMN plan VARCHAR(20) DEFAULT 'FREE' NOT NULL;

-- Tokens OpenAI reported for each message, summed over the message's model calls. Null for
-- messages from before this migration and for the offline model.
ALTER TABLE assistant_interactions ADD COLUMN input_tokens INTEGER;
ALTER TABLE assistant_interactions ADD COLUMN cached_tokens INTEGER;
ALTER TABLE assistant_interactions ADD COLUMN output_tokens INTEGER;

-- One row per account per day (Singapore time). The counters are what the daily limits are
-- checked against; the rest measures cost. Speech that came from the cache costs nothing and
-- isn't counted.
CREATE TABLE assistant_daily_usage (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL CONSTRAINT assistant_daily_usage_owner_id_fkey REFERENCES app_users(id),
  usage_date DATE NOT NULL,
  messages INTEGER DEFAULT 0 NOT NULL,
  transcriptions INTEGER DEFAULT 0 NOT NULL,
  spoken_replies INTEGER DEFAULT 0 NOT NULL,
  input_tokens BIGINT DEFAULT 0 NOT NULL,
  cached_tokens BIGINT DEFAULT 0 NOT NULL,
  output_tokens BIGINT DEFAULT 0 NOT NULL,
  transcribed_seconds INTEGER DEFAULT 0 NOT NULL,
  spoken_characters INTEGER DEFAULT 0 NOT NULL,
  CONSTRAINT assistant_daily_usage_owner_date_unique UNIQUE (owner_id, usage_date)
);

CREATE INDEX assistant_daily_usage_date_idx ON assistant_daily_usage(usage_date);
