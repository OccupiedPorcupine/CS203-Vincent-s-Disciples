-- The owner's own rules and information for the assistant (issue #151): supplier contacts and
-- order cut-offs, hygiene routines, helper rules. Only the extracted plain text is kept, never the
-- uploaded file. source is how it was made: TYPED on the Documents page, UPLOAD from a file, or
-- ASSISTANT for a note the owner confirmed in the assistant. index_status tracks whether its text
-- is searchable by the assistant yet (issue #152). Documents never change forecasts, prep or prices.
CREATE TABLE stall_documents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL CONSTRAINT stall_documents_owner_id_fkey REFERENCES app_users(id) ON DELETE CASCADE,
  title VARCHAR(120) NOT NULL,
  body VARCHAR(100000) NOT NULL,
  source VARCHAR(16) NOT NULL CONSTRAINT stall_documents_source_check CHECK (source IN ('TYPED', 'UPLOAD', 'ASSISTANT')),
  file_name VARCHAR(255),
  index_status VARCHAR(16) NOT NULL CONSTRAINT stall_documents_index_status_check CHECK (index_status IN ('PENDING', 'INDEXED', 'FAILED')),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX stall_documents_owner_id_idx ON stall_documents(owner_id);
