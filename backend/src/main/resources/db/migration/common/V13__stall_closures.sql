-- When a stall doesn't trade, so a closed day isn't read as a day with no sales and isn't forecast.
-- rest_days holds the weekly rest days: day_of_week 1 = Monday ... 7 = Sunday (ISO-8601).
-- closed_dates holds one-off closures (public holidays, hawker centre cleaning), with an optional reason.
-- A day with sales recorded still counts as open: the stall opened after all.
CREATE TABLE rest_days (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL CONSTRAINT rest_days_owner_id_fkey REFERENCES app_users(id),
  day_of_week INTEGER NOT NULL CONSTRAINT rest_days_day_of_week_check CHECK (day_of_week BETWEEN 1 AND 7),
  CONSTRAINT rest_days_owner_day_unique UNIQUE (owner_id, day_of_week)
);

CREATE TABLE closed_dates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL CONSTRAINT closed_dates_owner_id_fkey REFERENCES app_users(id),
  closed_date DATE NOT NULL,
  reason VARCHAR(100),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT closed_dates_owner_date_unique UNIQUE (owner_id, closed_date)
);
