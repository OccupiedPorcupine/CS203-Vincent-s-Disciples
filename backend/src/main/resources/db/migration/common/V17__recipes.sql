-- Recipes, for the prep list (issue #45): what one portion of each dish uses. An ingredient has
-- one unit (g, ml, pcs, ...) so its quantities across dishes can be added up. Ingredients are
-- named per owner; a name is unique ignoring case, which the service enforces through name_key.
CREATE TABLE ingredients (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL CONSTRAINT ingredients_owner_id_fkey REFERENCES app_users(id),
  name VARCHAR(60) NOT NULL,
  name_key VARCHAR(60) NOT NULL,
  unit VARCHAR(20) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT ingredients_owner_name_unique UNIQUE (owner_id, name_key)
);

CREATE TABLE dish_ingredients (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dish_id BIGINT NOT NULL CONSTRAINT dish_ingredients_dish_id_fkey REFERENCES dishes(id),
  ingredient_id BIGINT NOT NULL CONSTRAINT dish_ingredients_ingredient_id_fkey REFERENCES ingredients(id),
  owner_id BIGINT NOT NULL CONSTRAINT dish_ingredients_owner_id_fkey REFERENCES app_users(id),
  quantity NUMERIC(12, 3) NOT NULL CONSTRAINT dish_ingredients_quantity_check CHECK (quantity > 0),
  CONSTRAINT dish_ingredients_dish_ingredient_unique UNIQUE (dish_id, ingredient_id)
);

CREATE INDEX dish_ingredients_owner_id_idx ON dish_ingredients(owner_id);
CREATE INDEX dish_ingredients_ingredient_id_idx ON dish_ingredients(ingredient_id);
