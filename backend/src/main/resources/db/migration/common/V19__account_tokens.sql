-- Account security for real users (issue #49): email verification and password reset.
-- email_verified_at is set once the user opens the link sent to them; Google has already
-- verified the address of every Google account. A token is stored only as its SHA-256 hash, so
-- a database leak doesn't hand out working links; each one expires and can be used once.
ALTER TABLE app_users ADD COLUMN email_verified_at TIMESTAMP WITH TIME ZONE;
UPDATE app_users SET email_verified_at = CURRENT_TIMESTAMP WHERE google_id IS NOT NULL;

CREATE TABLE account_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL CONSTRAINT account_tokens_user_id_fkey REFERENCES app_users(id) ON DELETE CASCADE,
  purpose VARCHAR(30) NOT NULL CONSTRAINT account_tokens_purpose_check CHECK (purpose IN ('PASSWORD_RESET', 'EMAIL_VERIFICATION')),
  token_hash VARCHAR(64) NOT NULL CONSTRAINT account_tokens_token_hash_key UNIQUE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  used_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX account_tokens_user_id_idx ON account_tokens(user_id);
