-- Dashboard action cards the user dismissed (issue #53). A key names one card, e.g.
-- "missing-sales:2026-11-03", so a dismissed day stays hidden while a new one still shows.
CREATE TABLE dismissed_actions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL CONSTRAINT dismissed_actions_owner_id_fkey REFERENCES app_users(id),
  action_key VARCHAR(100) NOT NULL,
  dismissed_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT dismissed_actions_owner_key_unique UNIQUE (owner_id, action_key)
);
