-- What a dish sells for and costs to make, from a date onward (issue #43). A price change adds a
-- row instead of editing one, so past revenue keeps the price that applied on the day.
-- A dish's earliest row also covers sales before its date: setting a price once values the
-- history that was already recorded or imported. owner_id is kept for owner-scoped queries.
CREATE TABLE dish_prices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dish_id BIGINT NOT NULL CONSTRAINT dish_prices_dish_id_fkey REFERENCES dishes(id),
  owner_id BIGINT NOT NULL CONSTRAINT dish_prices_owner_id_fkey REFERENCES app_users(id),
  effective_from DATE NOT NULL,
  price NUMERIC(10, 2) NOT NULL CONSTRAINT dish_prices_price_check CHECK (price >= 0),
  unit_cost NUMERIC(10, 2) CONSTRAINT dish_prices_unit_cost_check CHECK (unit_cost >= 0),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT dish_prices_dish_date_unique UNIQUE (dish_id, effective_from)
);

CREATE INDEX dish_prices_owner_id_idx ON dish_prices(owner_id);
