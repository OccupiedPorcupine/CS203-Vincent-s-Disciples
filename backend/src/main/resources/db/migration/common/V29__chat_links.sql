-- Chat apps linked to an account (issue #99), so an owner can record sales from Telegram or
-- WhatsApp. external_id is the channel's ID for the chat (a Telegram chat ID, a WhatsApp phone
-- number). A chat belongs to at most one account, and an account has one chat per channel.
-- conversation_id and last_message_at keep a rolling assistant conversation per chat.
CREATE TABLE chat_links (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL CONSTRAINT chat_links_owner_id_fkey REFERENCES app_users(id) ON DELETE CASCADE,
  channel VARCHAR(20) NOT NULL CONSTRAINT chat_links_channel_check CHECK (channel IN ('TELEGRAM', 'WHATSAPP')),
  external_id VARCHAR(64) NOT NULL,
  display_name VARCHAR(100),
  linked_at TIMESTAMP WITH TIME ZONE NOT NULL,
  conversation_id VARCHAR(64),
  last_message_at TIMESTAMP WITH TIME ZONE,
  CONSTRAINT chat_links_channel_external_id_key UNIQUE (channel, external_id),
  CONSTRAINT chat_links_owner_channel_key UNIQUE (owner_id, channel)
);

-- Messages already handled, by the channel's message or update ID. Chat apps resend a message
-- when the reply is slow or fails, and a resent message must not be handled twice.
CREATE TABLE chat_inbound_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel VARCHAR(20) NOT NULL,
  message_id VARCHAR(64) NOT NULL,
  received_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT chat_inbound_messages_channel_message_id_key UNIQUE (channel, message_id)
);

CREATE INDEX chat_inbound_messages_received_at_idx ON chat_inbound_messages(received_at);

-- The one-time code that links a chat is an account token, like a password reset link.
ALTER TABLE account_tokens DROP CONSTRAINT account_tokens_purpose_check;
ALTER TABLE account_tokens ADD CONSTRAINT account_tokens_purpose_check
  CHECK (purpose IN ('PASSWORD_RESET', 'EMAIL_VERIFICATION', 'CHAT_LINK'));
