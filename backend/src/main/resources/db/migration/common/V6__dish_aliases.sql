-- Other names a user calls a dish by (e.g. "鸡饭" or "roast chicken" for "Roasted chicken rice"),
-- so spoken or typed names can be matched to the right dish.
-- normalized_alias is the alias trimmed, lowercased and Unicode-normalized by the application.
-- It is unique per owner, so one name always points to one dish for that user.
CREATE TABLE dish_aliases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dish_id BIGINT NOT NULL CONSTRAINT dish_aliases_dish_id_fkey REFERENCES dishes(id),
  owner_id BIGINT NOT NULL CONSTRAINT dish_aliases_owner_id_fkey REFERENCES app_users(id),
  alias VARCHAR(100) NOT NULL,
  normalized_alias VARCHAR(100) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT dish_aliases_owner_alias_unique UNIQUE (owner_id, normalized_alias)
);

CREATE INDEX dish_aliases_dish_id_idx ON dish_aliases(dish_id);
