-- NEA's hawker centres and the days they close for cleaning or works, from data.gov.sg's "Dates of
-- Hawker Centres Closure" (refreshed daily by HawkerCentreSyncService). Shared by every stall, like
-- public_holidays. A stall linked to a centre treats its closures as closed days.
CREATE TABLE hawker_centres (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  address VARCHAR(300),
  synced_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT hawker_centres_name_unique UNIQUE (name)
);

-- kind is CLEANING (the quarterly cleaning) or WORKS (repairs, redevelopment and the like).
-- remarks is NEA's note, e.g. "Only Cooked Food Section is closed"; null when NEA wrote "nil".
CREATE TABLE hawker_centre_closures (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hawker_centre_id BIGINT NOT NULL CONSTRAINT hawker_centre_closures_centre_id_fkey REFERENCES hawker_centres(id) ON DELETE CASCADE,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  kind VARCHAR(20) NOT NULL CONSTRAINT hawker_centre_closures_kind_check CHECK (kind IN ('CLEANING', 'WORKS')),
  remarks VARCHAR(300),
  CONSTRAINT hawker_centre_closures_dates_check CHECK (end_date >= start_date)
);

CREATE INDEX hawker_centre_closures_centre_idx ON hawker_centre_closures (hawker_centre_id);

-- The hawker centre a stall is in, if the owner has picked one.
CREATE TABLE stall_hawker_centres (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL CONSTRAINT stall_hawker_centres_owner_id_fkey REFERENCES app_users(id),
  hawker_centre_id BIGINT NOT NULL CONSTRAINT stall_hawker_centres_centre_id_fkey REFERENCES hawker_centres(id),
  CONSTRAINT stall_hawker_centres_owner_unique UNIQUE (owner_id)
);

-- Days NEA closes the stall's centre but the owner says the stall opens anyway.
CREATE TABLE nea_open_days (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL CONSTRAINT nea_open_days_owner_id_fkey REFERENCES app_users(id),
  open_date DATE NOT NULL,
  CONSTRAINT nea_open_days_owner_date_unique UNIQUE (owner_id, open_date)
);
