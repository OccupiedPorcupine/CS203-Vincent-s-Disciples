CREATE TABLE training_data_sources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL CONSTRAINT training_data_sources_owner_id_fkey REFERENCES app_users(id),
  original_filename VARCHAR(255) NOT NULL,
  content_type VARCHAR(255) NOT NULL,
  size_bytes BIGINT NOT NULL,
  sha256 VARCHAR(64) NOT NULL,
  stored_path VARCHAR(1024) NOT NULL,
  status VARCHAR(32) NOT NULL,
  used_by_model BOOLEAN NOT NULL,
  uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT training_source_owner_hash_unique UNIQUE (owner_id, sha256)
);

CREATE INDEX training_data_sources_owner_id_idx ON training_data_sources(owner_id);
