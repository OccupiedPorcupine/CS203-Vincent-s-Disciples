-- Sold-out times and leftovers (issue #50). On a day a dish sold out, quantity_sold is what the
-- stall had, not what customers wanted, so forecasts count that day as higher demand. Leftovers
-- are portions prepared but not sold (waste). Both are optional: null means not recorded.
ALTER TABLE daily_sales ADD COLUMN sold_out_at TIME;
ALTER TABLE daily_sales ADD COLUMN leftover_quantity INTEGER;
ALTER TABLE daily_sales ADD CONSTRAINT daily_sales_leftover_quantity_check CHECK (leftover_quantity >= 0);

-- When the stall trades each open day, used to tell how early a dish sold out. closes_at before
-- opens_at means the stall closes after midnight (a supper stall open 18:00 to 02:00).
CREATE TABLE trading_hours (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL CONSTRAINT trading_hours_owner_id_fkey REFERENCES app_users(id),
  opens_at TIME NOT NULL,
  closes_at TIME NOT NULL,
  CONSTRAINT trading_hours_owner_unique UNIQUE (owner_id),
  CONSTRAINT trading_hours_not_empty_check CHECK (opens_at <> closes_at)
);
