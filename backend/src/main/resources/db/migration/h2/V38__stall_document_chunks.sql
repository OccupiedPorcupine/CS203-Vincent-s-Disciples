-- Searchable chunks of each stall document (issue #152). H2 has no vector type, so the embedding
-- is stored as bytes (4 per dimension) and compared in Java (InMemoryDocumentSearch). The Postgres
-- copy of this migration, with pgvector and an HNSW index, is in ../postgresql/.
CREATE TABLE stall_document_chunks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id BIGINT NOT NULL CONSTRAINT stall_document_chunks_document_id_fkey REFERENCES stall_documents(id) ON DELETE CASCADE,
  owner_id BIGINT NOT NULL CONSTRAINT stall_document_chunks_owner_id_fkey REFERENCES app_users(id) ON DELETE CASCADE,
  chunk_index INTEGER NOT NULL,
  content VARCHAR(8000) NOT NULL,
  embedding_model VARCHAR(64) NOT NULL,
  embedding VARBINARY(16384) NOT NULL,
  CONSTRAINT stall_document_chunks_document_chunk_key UNIQUE (document_id, chunk_index)
);

CREATE INDEX stall_document_chunks_owner_id_idx ON stall_document_chunks(owner_id);
