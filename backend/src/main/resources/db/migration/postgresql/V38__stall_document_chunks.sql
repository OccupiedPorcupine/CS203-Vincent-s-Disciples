-- Searchable chunks of each stall document (issue #152), with their embeddings in a pgvector
-- column and an HNSW index for cosine distance. owner_id is copied from the document so every
-- search can filter by owner without a join. The H2 copy of this migration is in ../h2/.
-- 1536 is app.documents.embedding-dimensions (text-embedding-3-small); changing it needs a new migration.
--
-- Supabase keeps extensions in the "extensions" schema. If pgvector was already enabled
-- somewhere else, that schema is used instead.
CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA extensions;

DO $$
DECLARE vector_schema text;
BEGIN
  SELECT n.nspname INTO vector_schema
    FROM pg_extension e JOIN pg_namespace n ON n.oid = e.extnamespace
   WHERE e.extname = 'vector';

  EXECUTE format($table$
    CREATE TABLE stall_document_chunks (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      document_id BIGINT NOT NULL CONSTRAINT stall_document_chunks_document_id_fkey REFERENCES stall_documents(id) ON DELETE CASCADE,
      owner_id BIGINT NOT NULL CONSTRAINT stall_document_chunks_owner_id_fkey REFERENCES app_users(id) ON DELETE CASCADE,
      chunk_index INTEGER NOT NULL,
      content VARCHAR(8000) NOT NULL,
      embedding_model VARCHAR(64) NOT NULL,
      embedding %1$I.vector(1536) NOT NULL,
      CONSTRAINT stall_document_chunks_document_chunk_key UNIQUE (document_id, chunk_index)
    )$table$, vector_schema);

  EXECUTE format('CREATE INDEX stall_document_chunks_embedding_idx ON stall_document_chunks '
      'USING hnsw (embedding %1$I.vector_cosine_ops)', vector_schema);
END $$;

CREATE INDEX stall_document_chunks_owner_id_idx ON stall_document_chunks(owner_id);

ALTER TABLE stall_document_chunks ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE api_role text;
BEGIN
  FOREACH api_role IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = api_role) THEN
      EXECUTE format('REVOKE ALL ON stall_document_chunks FROM %I', api_role);
    END IF;
  END LOOP;
END $$;
